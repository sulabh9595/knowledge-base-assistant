def parse_pytest_xml(xml_path: Path) -> Optional[Dict[str, Any]]:
    """Parses JUnit XML report generated by pytest."""
    if not xml_path.exists():
        return None
    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()

        suite = root.find("testsuite") if root.tag == "testsuites" else root
        if suite is None:
            return None

        tests = int(suite.attrib.get("tests", 0))
        failures = int(suite.attrib.get("failures", 0))
        errors = int(suite.attrib.get("errors", 0))
        skipped = int(suite.attrib.get("skipped", 0))
        duration = float(suite.attrib.get("time", 0.0))
        timestamp = suite.attrib.get("timestamp", "")

        passed = max(0, tests - (failures + errors + skipped))
        pass_rate = (passed / tests * 100) if tests > 0 else 0.0

        test_cases = []
        for tc in suite.findall("testcase"):
            classname = tc.attrib.get("classname", "")
            name = tc.attrib.get("name", "")
            time_sec = float(tc.attrib.get("time", 0.0))

            failure = tc.find("failure")
            error = tc.find("error")
            skp = tc.find("skipped")

            if failure is not None:
                status = "FAILED"
                message = failure.attrib.get("message", "")
                details = failure.text or message
            elif error is not None:
                status = "ERROR"
                message = error.attrib.get("message", "")
                details = error.text or message
            elif skp is not None:
                status = "SKIPPED"
                message = skp.attrib.get("message", "")
                details = skp.text or message
            else:
                status = "PASSED"
                details = ""

            test_cases.append({
                "classname": classname,
                "name": name,
                "duration": time_sec,
                "status": status,
                "details": details
            })

        return {
            "summary": {
                "tests": tests,
                "passed": passed,
                "failures": failures,
                "errors": errors,
                "skipped": skipped,
                "duration": duration,
                "pass_rate": pass_rate,
                "timestamp": timestamp
            },
            "cases": test_cases
        }
    except Exception as exc:
        return None


def render_pytest_dashboard():
    """Renders the Pytest Test Suite Results Dashboard in Tab 7."""
    base_dir = Path(__file__).resolve().parents[1]
    results_dir = base_dir / "eval_results"
    xml_report_path = results_dir / "pytest_report.xml"

    st.subheader("🧪 Pytest & Test Suite Results Inspector")
    st.markdown(
        "Interactive test execution and status breakdown for unit, integration, and evaluation tests "
        "stored in the `tests/` directory."
    )

    col_btn1, col_btn2, col_btn3 = st.columns([1.5, 1.5, 2])

    with col_btn1:
        if st.button("▶️ Run Unit Tests (Fast)", key="run_fast_pytest_btn"):
            with st.spinner("Running fast pytest suite (excluding evals)..."):
                try:
                    cmd = [
                        sys.executable, "-m", "pytest", "tests/",
                        "--ignore=tests/evals",
                        f"--junitxml={xml_report_path}"
                    ]
                    res = subprocess.run(cmd, cwd=base_dir, capture_output=True, text=True)
                    if res.returncode == 0:
                        st.success("Fast unit test suite completed successfully!")
                    else:
                        st.warning(f"Pytest finished with exit code {res.returncode}.")
                except Exception as exc:
                    st.error(f"Failed to run pytest: {exc}")

    with col_btn2:
        if st.button("▶️ Run Full Suite (All Tests)", key="run_full_pytest_btn"):
            with st.spinner("Running complete pytest suite (including evals)..."):
                try:
                    cmd = [
                        sys.executable, "-m", "pytest", "tests/",
                        f"--junitxml={xml_report_path}"
                    ]
                    res = subprocess.run(cmd, cwd=base_dir, capture_output=True, text=True)
                    if res.returncode == 0:
                        st.success("Full test suite completed successfully!")
                    else:
                        st.warning(f"Pytest finished with exit code {res.returncode}.")
                except Exception as exc:
                    st.error(f"Failed to run pytest: {exc}")

    with col_btn3:
        if xml_report_path.exists():
            st.caption(f"Last XML Report Generated: `{xml_report_path.name}`")
        else:
            st.caption("No JUnit XML report found yet. Click a run button above.")

    st.markdown("---")

    report_data = parse_pytest_xml(xml_report_path)

    if report_data is None:
        st.info("No XML test report available yet. Run tests above or via CLI (`pytest tests/ --junitxml=eval_results/pytest_report.xml`).")
    else:
        summary = report_data["summary"]
        cases = report_data["cases"]

        m_col1, m_col2, m_col3, m_col4, m_col5 = st.columns(5)
        m_col1.metric("Total Tests", summary["tests"])
        m_col2.metric("Passed Tests", summary["passed"])
        m_col3.metric("Failed / Errors", summary["failures"] + summary["errors"])
        m_col4.metric("Pass Rate", f"{summary['pass_rate']:.1f}%")
        m_col5.metric("Execution Time", f"{summary['duration']:.2f}s")

        st.markdown("---")

        f_col1, f_col2 = st.columns([2, 1])
        with f_col1:
            modules = sorted(list(set(c["classname"] for c in cases)))
            selected_module = st.selectbox("Filter by Module", ["All Modules"] + modules, key="pytest_mod_filter")
        with f_col2:
            selected_status = st.selectbox("Filter by Status", ["All Statuses", "PASSED", "FAILED", "SKIPPED"], key="pytest_status_filter")

        filtered_cases = cases
        if selected_module != "All Modules":
            filtered_cases = [c for c in filtered_cases if c["classname"] == selected_module]
        if selected_status != "All Statuses":
            filtered_cases = [c for c in filtered_cases if c["status"] == selected_status]

        st.subheader(f"Test Cases ({len(filtered_cases)} / {len(cases)})")

        for idx, c in enumerate(filtered_cases, 1):
            status = c["status"]
            if status == "PASSED":
                badge = "🟢 PASSED"
            elif status in ("FAILED", "ERROR"):
                badge = "🔴 FAILED"
            else:
                badge = "🟡 SKIPPED"

            mod_short = c["classname"].split(".")[-1] if "." in c["classname"] else c["classname"]
            title = f"{idx}. [{mod_short}] {c['name']} ({badge}) - {c['duration']:.3f}s"

            with st.expander(title):
                st.markdown(f"**Module:** `{c['classname']}`")
                st.markdown(f"**Test Function:** `{c['name']}`")
                st.markdown(f"**Status:** `{c['status']}` | **Duration:** `{c['duration']:.3f}s`")
                if c["details"]:
                    st.markdown("#### Execution Output / Stack Trace")
                    st.code(c["details"], language="python")


